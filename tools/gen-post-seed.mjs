// Turns content/blog/*.md into migrations/0007_seed_posts.sql, so the posts
// the blog launched with live in D1 like every later post and can be edited in
// the admin. Re-run after editing a seed file:
//
//   node tools/gen-post-seed.mjs
//
// The generated INSERTs are OR IGNORE on slug: the deploy re-runs every
// migration, and a seeded post that has since been edited in the admin must
// never be overwritten by its original text.

import fs from 'node:fs';
import path from 'node:path';

const SRC = 'content/blog';
const OUT = 'migrations/0007_seed_posts.sql';

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

function parse(file) {
  const raw = fs.readFileSync(path.join(SRC, file), 'utf8');
  const m = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error(`${file}: missing front matter`);
  const meta = Object.fromEntries(
    m[1].split('\n').filter(Boolean).map((line) => {
      const i = line.indexOf(':');
      return [line.slice(0, i).trim(), line.slice(i + 1).trim()];
    })
  );
  if (!meta.title || !meta.date) throw new Error(`${file}: needs title and date`);
  return {
    slug: file.replace(/\.md$/, ''),
    title: meta.title,
    description: meta.description || '',
    body: m[2].trim(),
    at: Date.parse(`${meta.date}T09:00:00Z`),
  };
}

const posts = fs.readdirSync(SRC).filter((f) => f.endsWith('.md')).sort().map(parse);

const sql = `-- GENERATED by tools/gen-post-seed.mjs from content/blog/*.md — do not edit by hand.
-- The three posts the blog launched with, moved out of static HTML and into
-- D1 so they can be edited in the admin like any other post.
-- OR IGNORE: re-running the deploy must never undo an edit made in the admin.
${posts
  .map(
    (p) => `
INSERT OR IGNORE INTO posts (slug, title, description, body, published, created_at, updated_at)
VALUES (${q(p.slug)}, ${q(p.title)}, ${q(p.description)}, ${q(p.body)}, 1, ${p.at}, ${p.at});`
  )
  .join('\n')}
`;

fs.writeFileSync(OUT, sql);
console.log(`${OUT}: ${posts.length} posts (${posts.map((p) => p.slug).join(', ')})`);
