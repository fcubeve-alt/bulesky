// Turns content/blog/*.md into a migration, so a post written as a file lands
// in D1 like every other post and can be edited in the admin afterwards.
//
//   node tools/gen-post-seed.mjs
//
// One post, one file, one INSERT. D1 executes a migration file as a single
// unit and rolls the whole thing back if any statement fails, so anything
// sharing a file shares its failures — that is what broke the site once
// already (see migrations/0014). The three posts the blog launched with are
// still together in 0007 because they are long since applied; everything new
// gets its own.
//
// A slug that already appears in any migration is skipped rather than rewritten.
// The post lives in D1 now and may well have been edited in the admin — this
// tool's job ends the moment the post exists there.
//
// Every INSERT is OR IGNORE for the same reason: the deploy re-runs every
// migration, and a seeded post that has since been edited must never be
// overwritten by its original text.
import fs from 'node:fs';
import path from 'node:path';

const SRC = 'content/blog';
const MIGRATIONS = 'migrations';

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

function parse(file) {
  const raw = fs.readFileSync(path.join(SRC, file), 'utf8');
  const m = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error(`${file}: missing front matter`);
  const meta = Object.fromEntries(
    m[1].split('\n').filter(Boolean).map((line) => {
      const i = line.indexOf(':');
      return [line.slice(0, i).trim(), line.slice(i + 1).trim()];
    })
  );
  if (!meta.title || !meta.date) throw new Error(`${file}: needs title and date`);
  return {
    slug: file.replace(/\.md$/, ''),
    title: meta.title,
    description: meta.description || '',
    body: m[2].trim(),
    at: Date.parse(`${meta.date}T09:00:00Z`),
  };
}

const existing = fs
  .readdirSync(MIGRATIONS)
  .filter((f) => f.endsWith('.sql'))
  .map((f) => fs.readFileSync(path.join(MIGRATIONS, f), 'utf8'))
  .join('\n');

// Next free number, so a new post sorts after everything already applied —
// the deploy runs migrations in filename order.
function nextNumber() {
  const used = fs
    .readdirSync(MIGRATIONS)
    .map((f) => parseInt(f.slice(0, 4), 10))
    .filter(Number.isFinite);
  return String(Math.max(0, ...used) + 1).padStart(4, '0');
}

const posts = fs.readdirSync(SRC).filter((f) => f.endsWith('.md')).sort().map(parse);
const added = [];

for (const p of posts) {
  if (existing.includes(`'${p.slug}'`)) continue;
  const name = `${nextNumber()}_post_${p.slug.replace(/-/g, '_').slice(0, 40)}.sql`;
  const sql = `-- GENERATED by tools/gen-post-seed.mjs from ${SRC}/${p.slug}.md
-- One post, one statement — see 0014. OR IGNORE so re-running the deploy can
-- never overwrite an edit made in the admin.

INSERT OR IGNORE INTO posts (slug, title, description, body, published, created_at, updated_at)
VALUES (${q(p.slug)}, ${q(p.title)}, ${q(p.description)}, ${q(p.body)}, 1, ${p.at}, ${p.at});
`;
  fs.writeFileSync(path.join(MIGRATIONS, name), sql);
  added.push(name);
}

console.log(
  added.length
    ? `wrote ${added.length} migration(s): ${added.join(', ')}`
    : `nothing new — all ${posts.length} posts are already in a migration`
);
